-- "Meus modelos": NPCs, monstros e locais que o Mestre guarda na conta e reutiliza em qualquer mesa.
-- A imagem do modelo é uma cópia própria (images sem campaign_id), para não sumir se a mesa de origem for excluída.
CREATE TABLE gm_templates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('npc', 'monster', 'location')),
  name text NOT NULL,
  name_key text NOT NULL,
  description text NOT NULL DEFAULT '',
  image_url text,
  stats_json text NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, kind, name_key)
);
CREATE INDEX idx_gm_templates_user ON gm_templates (user_id, kind, name);
