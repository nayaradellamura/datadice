-- Esquema inicial do DataDice no PostgreSQL: modo Solo (Mestre IA) e a base do modo Grupo (Mestre humano).
-- Datas em timestamptz (UTC). Colunas *_json guardam JSON como texto, igual à versão SQLite.

CREATE EXTENSION IF NOT EXISTS unaccent SCHEMA public;

-- unaccent() não é IMMUTABLE e por isso não entra em índice; este invólucro fixa o dicionário.
CREATE FUNCTION dd_unaccent(text) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
  AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$;

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  -- bcrypt. Vazio só no usuário local de antes do login, até o admin assumir essa conta.
  password_hash text,
  -- Papel no sistema. Mestre e jogador são papéis por campanha (campaign_members).
  role text NOT NULL DEFAULT 'player' CHECK (role IN ('admin', 'player')),
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Arquivos de imagem guardados no próprio banco (retratos, ilustrações, uploads do Mestre).
-- Servidos em /images/<name>; o nome é aleatório e não pode ser adivinhado.
CREATE TABLE images (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  campaign_id integer,
  mime text NOT NULL CHECK (mime IN ('image/png', 'image/jpeg', 'image/webp')),
  size integer NOT NULL,
  data bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE characters (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name text NOT NULL,
  race text NOT NULL,
  class text NOT NULL,
  str integer NOT NULL,
  dex integer NOT NULL,
  con integer NOT NULL,
  "int" integer NOT NULL,
  wis integer NOT NULL,
  cha integer NOT NULL,
  backstory text NOT NULL DEFAULT '',
  avatar_url text,
  level integer NOT NULL DEFAULT 1,
  background text NOT NULL DEFAULT '',
  alignment text NOT NULL DEFAULT '',
  player_name text NOT NULL DEFAULT '',
  xp integer NOT NULL DEFAULT 0,
  armor_class integer NOT NULL DEFAULT 10,
  speed text NOT NULL DEFAULT '9 m',
  hit_die integer NOT NULL DEFAULT 8,
  max_hp integer NOT NULL DEFAULT 1,
  sheet_json text NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_characters_user ON characters (user_id);

-- solo: Mestre IA, um jogador. grupo: Mestre humano, sem IA, até 6 jogadores.
CREATE TABLE campaigns (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  mode text NOT NULL DEFAULT 'solo' CHECK (mode IN ('solo', 'grupo')),
  name text NOT NULL,
  system_prompt text NOT NULL DEFAULT '',
  world_description text NOT NULL DEFAULT '',
  -- Código que o Mestre compartilha (ex.: DADO-7K3Q). Só nas mesas em grupo.
  join_code text UNIQUE,
  join_open boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_campaigns_user ON campaigns (user_id);
ALTER TABLE images ADD FOREIGN KEY (campaign_id) REFERENCES campaigns(id) ON DELETE CASCADE;

-- Quem está em cada mesa e com qual papel. pendente: pediu para entrar e espera o Mestre aprovar.
CREATE TABLE campaign_members (
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role text NOT NULL CHECK (role IN ('mestre', 'jogador')),
  status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'ativo', 'removido')),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (campaign_id, user_id)
);
CREATE INDEX idx_members_user ON campaign_members (user_id, status);

-- A ficha ligada a uma campanha. O estado de jogo (PV, itens, condições) é separado por campanha.
CREATE TABLE campaign_characters (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  character_id integer NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
  current_hp integer NOT NULL,
  max_hp integer NOT NULL,
  inventory_json text NOT NULL DEFAULT '[]',
  status text NOT NULL DEFAULT 'active',
  temp_hp integer NOT NULL DEFAULT 0,
  death_successes integer NOT NULL DEFAULT 0,
  death_failures integer NOT NULL DEFAULT 0,
  inspiration integer NOT NULL DEFAULT 0,
  hit_dice_used integer NOT NULL DEFAULT 0,
  coins_json text NOT NULL DEFAULT '{}',
  spell_slots_used_json text NOT NULL DEFAULT '{}',
  conditions_json text NOT NULL DEFAULT '[]',
  UNIQUE (campaign_id, character_id)
);
CREATE INDEX idx_campaign_characters_character ON campaign_characters (character_id);

-- Chat do Solo e das mesas.
-- kind: fala, ooc (fora do personagem), rolagem, narracao, sistema (vazio nas mensagens do Solo antigo).
-- visibility: all (todos), gm (só o Mestre: rolagens secretas e notas), private (autor, destinatário e Mestre).
CREATE TABLE messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  sender_type text NOT NULL CHECK (sender_type IN ('player', 'gm', 'system')),
  sender_name text NOT NULL,
  message_text text NOT NULL,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  character_id integer REFERENCES characters(id) ON DELETE SET NULL,
  kind text,
  visibility text NOT NULL DEFAULT 'all' CHECK (visibility IN ('all', 'gm', 'private')),
  recipient_user_id integer REFERENCES users(id) ON DELETE SET NULL,
  image_id integer REFERENCES images(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  search tsvector GENERATED ALWAYS AS (to_tsvector('simple', dd_unaccent(message_text))) STORED
);
CREATE INDEX idx_messages_campaign ON messages (campaign_id, id);
CREATE INDEX idx_messages_search ON messages USING gin (search);

CREATE TABLE token_logs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "timestamp" timestamptz NOT NULL DEFAULT now(),
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  campaign_id integer REFERENCES campaigns(id) ON DELETE SET NULL,
  -- turn, roll, session, summary ou campaign.
  kind text,
  model_name text NOT NULL,
  prompt_tokens integer NOT NULL DEFAULT 0,
  completion_tokens integer NOT NULL DEFAULT 0,
  total_tokens integer NOT NULL DEFAULT 0
);
CREATE INDEX idx_token_logs_user ON token_logs (user_id, "timestamp");

-- Caderno do Mestre (Solo): memória de longo prazo, uma ficha por PdM, local, missão etc.
CREATE TABLE campaign_memories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  type text NOT NULL CHECK (type IN ('npc', 'location', 'quest', 'item', 'faction', 'event', 'fact')),
  name text NOT NULL,
  name_key text NOT NULL,
  content text NOT NULL,
  importance integer NOT NULL DEFAULT 3 CHECK (importance BETWEEN 1 AND 5),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'resolved', 'dead', 'lost')),
  pinned integer NOT NULL DEFAULT 0,
  source text NOT NULL DEFAULT 'ai' CHECK (source IN ('ai', 'user')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  search tsvector GENERATED ALWAYS AS (
    setweight(to_tsvector('simple', dd_unaccent(name)), 'A') || setweight(to_tsvector('simple', dd_unaccent(content)), 'B')
  ) STORED,
  UNIQUE (campaign_id, name_key)
);
CREATE INDEX idx_memories_search ON campaign_memories USING gin (search);

CREATE TABLE campaign_summaries (
  campaign_id integer PRIMARY KEY REFERENCES campaigns(id) ON DELETE CASCADE,
  summary_text text NOT NULL DEFAULT '',
  last_message_id integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE campaign_sessions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('intro', 'recap', 'legacy')),
  first_message_id integer NOT NULL,
  ended_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_campaign_sessions ON campaign_sessions (campaign_id, id);

-- Biblioteca da campanha. No Solo, a IA cria e ilustra; no Grupo, o Mestre cadastra à mão.
-- revealed: no Grupo começa oculto e o Mestre revela quando quiser.
CREATE TABLE npcs (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  name text NOT NULL,
  name_key text NOT NULL,
  description text NOT NULL DEFAULT '',
  image_prompt text NOT NULL DEFAULT '',
  image_url text,
  image_status text NOT NULL DEFAULT 'pending' CHECK (image_status IN ('pending', 'ready', 'failed')),
  image_error text,
  revealed boolean NOT NULL DEFAULT true,
  stats_json text NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (campaign_id, name_key)
);
CREATE TABLE monsters (LIKE npcs INCLUDING DEFAULTS INCLUDING CONSTRAINTS);
ALTER TABLE monsters ADD PRIMARY KEY (id), ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY,
  ADD FOREIGN KEY (campaign_id) REFERENCES campaigns(id) ON DELETE CASCADE, ADD UNIQUE (campaign_id, name_key);
CREATE TABLE locations (LIKE npcs INCLUDING DEFAULTS INCLUDING CONSTRAINTS);
ALTER TABLE locations ADD PRIMARY KEY (id), ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY,
  ADD FOREIGN KEY (campaign_id) REFERENCES campaigns(id) ON DELETE CASCADE, ADD UNIQUE (campaign_id, name_key);

CREATE TABLE message_illustrations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id integer NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('npc', 'monster', 'location')),
  entity_id integer NOT NULL,
  UNIQUE (message_id, kind, entity_id)
);
CREATE INDEX idx_message_illustrations ON message_illustrations (kind, entity_id);

-- Notas privadas do Mestre (modo Grupo).
CREATE TABLE gm_notes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id integer NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL DEFAULT '',
  body text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_gm_notes_campaign ON gm_notes (campaign_id);

-- Ordem de iniciativa (modo Grupo). entries_json: [{ name, initiative, character_id?, monster_id?, hp?, max_hp? }].
CREATE TABLE campaign_initiative (
  campaign_id integer PRIMARY KEY REFERENCES campaigns(id) ON DELETE CASCADE,
  round integer NOT NULL DEFAULT 1,
  turn_index integer NOT NULL DEFAULT 0,
  entries_json text NOT NULL DEFAULT '[]',
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Trechos pesquisáveis dos livros de regras ("npm run rules:ingest").
CREATE TABLE rule_chunks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book text NOT NULL,
  page integer NOT NULL,
  text text NOT NULL,
  search tsvector GENERATED ALWAYS AS (to_tsvector('simple', dd_unaccent(text))) STORED
);
CREATE INDEX idx_rule_chunks_book ON rule_chunks (book, page, id);
CREATE INDEX idx_rule_chunks_search ON rule_chunks USING gin (search);
